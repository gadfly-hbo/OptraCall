// Author acceptance through the normal UI. Run only on an isolated QA Host/UI
// on 4183, with a loopback synthetic provider in the `provider` query parameter.
// HTTP/native tests separately verify actual tool computation and fixed bytes.
async (page) => {
  const initial = new URL(page.url()), origin = initial.origin;
  const provider = initial.searchParams.get('provider');
  if (origin !== 'http://127.0.0.1:4183' || !provider || new URL(provider).hostname !== '127.0.0.1')
    throw new Error('Use isolated QA UI 4183 and its loopback synthetic provider.');
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const api = async (route, method = 'GET', data) => {
    const response = await page.request.fetch(origin + route, { method, headers: { origin, 'x-optracall-client': '1' }, ...(data === undefined ? {} : { data }) });
    assert(response.ok(), `${method} ${route}: ${response.status()} ${await response.text()}`);
    return response.json();
  };
  const metrics = async () => (await page.request.get(new URL('/__qa', provider).href)).json();
  const checks = [], errors = [], outbound = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (new URL(request.url()).hostname !== '127.0.0.1') outbound.push(request.url()); });
  await api('/api/configuration', 'PUT', { name: 'M2浏览器合成配置', provider: 'openai-compatible',
    baseUrl: provider, model: 'synthetic-m2-browser', apiKey: 'synthetic-m2-browser-only' });
  const conceptTitle = `M2合成概念说明 ${Date.now()}`;
  const concept = await api('/api/enterprise-materials', 'POST', { title: conceptTitle, body: 'M2_UI_CONCEPT_V1：金额单位为元，退款口径未知；仅合成技术资料。' });
  const enabled = await api(`/api/enterprise-materials/${concept.material.id}/enable`, 'POST', { expectedVersion: concept.material.version });
  const conceptRef = { storeId: enabled.storeId, materialId: concept.material.id, revisionId: enabled.material.activeRevisionId };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(origin);
  const expand = page.getByRole('button', { name: '展开侧栏', exact: true });
  if (await expand.isVisible()) await expand.click();
  const projectName = `M2同任务来源 ${Date.now()}`, taskName = '原制度讨论任务';
  await page.getByRole('button', { name: '新建项目', exact: true }).click();
  const projectDialog = page.getByRole('dialog', { name: '新建项目', exact: true });
  await projectDialog.getByRole('textbox', { name: '项目名称', exact: true }).fill(projectName);
  await projectDialog.getByRole('button', { name: '创建项目', exact: true }).click();
  await projectDialog.waitFor({ state: 'detached' });
  await page.getByRole('button', { name: '新建第一个任务', exact: true }).click();
  const taskDialog = page.getByRole('dialog', { name: '新建任务', exact: true });
  await taskDialog.getByRole('textbox', { name: '任务名称', exact: true }).fill(taskName);
  await taskDialog.getByRole('button', { name: '创建任务', exact: true }).click();
  await taskDialog.waitFor({ state: 'detached' });
  await page.getByRole('heading', { name: taskName, exact: true, level: 1 }).waitFor();
  const owner = new URL(page.url()), projectId = owner.searchParams.get('project'), taskId = owner.searchParams.get('task');
  assert(projectId && taskId, 'The normal task route must preserve actual project/task identities');
  const message = page.getByRole('textbox', { name: '消息', exact: true });
  const before = (await metrics()).requestCount;
  await message.fill('先讨论合成制度中的金额单位和未知条件，尚无明细表。');
  await page.waitForFunction(() => document.querySelector('.send-button')?.disabled === false);
  await message.press('Enter');
  await page.getByRole('button', { name: '将最新回复保存为最终报告', exact: true }).waitFor();
  assert((await metrics()).requestCount === before + 1, 'A task without Case, RAP, SAP or a dataset can run');
  checks.push('No-table policy discussion starts through original task UI without mandatory forms');
  const files = page.getByRole('complementary', { name: '项目文件', exact: true });
  await files.getByLabel('上传位置', { exact: true }).selectOption('020_clean');
  await files.getByLabel('选择上传文件', { exact: true }).setInputFiles({ name: 'm2-sales.csv', mimeType: 'text/csv',
    buffer: Buffer.from('id,amount\nsynthetic-a,10\nsynthetic-b,20\n') });
  await files.getByRole('status').filter({ hasText: '上传已保存到分析区' }).waitFor();
  await files.getByRole('button', { name: '数据说明与来源 m2-sales.csv', exact: true }).click();
  await page.getByRole('heading', { name: '数据说明与来源', exact: true }).waitFor();
  assert((await metrics()).requestCount === before + 1, 'Uploading/opening data explanation cannot run an Agent');
  const panel = page.getByRole('region', { name: '数据说明与来源', exact: true });
  await panel.getByLabel('数据名称', { exact: true }).fill('合成销售输入');
  const previewResponse = page.waitForResponse(response => response.url().includes(`/api/projects/${projectId}/data-context/preview`) && response.request().method() === 'POST');
  await panel.getByRole('button', { name: '预览固定输入', exact: true }).click();
  assert((await previewResponse).status() === 200, 'Explicit input preview must succeed through the original file UI');
  const fixedResponse = page.waitForResponse(response => response.url().endsWith(`/api/projects/${projectId}/data-context/inputs`) && response.request().method() === 'POST');
  await panel.getByRole('button', { name: '固定为新版本', exact: true }).click();
  assert((await fixedResponse).status() === 201, 'Explicit freeze creates a new fixed input version');
  await panel.getByRole('button', { name: '读取固定内容', exact: true }).click();
  assert(await panel.locator('pre').innerText() === 'id,amount\nsynthetic-a,10\nsynthetic-b,20\n', 'Fixed UI readback must preserve all original bytes');
  checks.push('Explicit 020 input preview, fixed version and historical byte readback');
  await panel.getByRole('combobox', { name: '观察范围', exact: true }).selectOption('partial');
  await panel.getByLabel('观察限制', { exact: true }).fill('仅人工填写，未逐行扫描，记录计数未知。');
  await panel.getByLabel('记录计数规则', { exact: true }).fill('CSV逻辑记录不含表头；本次未扫描，空记录处理亦未知。');
  await panel.getByLabel('解释正文', { exact: true }).fill('M2_UI_ROW_MEANING：每行合成销售，退款口径未知。');
  await panel.getByRole('button', { name: '添加业务解释', exact: true }).click();
  await panel.getByLabel('映射字段位置', { exact: true }).fill('1');
  const concepts = panel.getByRole('listbox', { name: '概念说明来源', exact: true });
  const chosenConcept = concepts.getByRole('option', { name: new RegExp(`${conceptTitle}.*${conceptRef.revisionId.slice(0, 8)}`) });
  await concepts.selectOption(await chosenConcept.getAttribute('value'));
  await panel.getByRole('button', { name: '添加字段映射', exact: true }).click();
  assert(await panel.getByRole('button', { name: '用于本轮', exact: true }).isDisabled(), 'An unsaved explanation draft must not be represented as the saved selection');
  const descriptionResponse = page.waitForResponse(response => response.url().endsWith(`/api/projects/${projectId}/data-context/descriptions`) && response.request().method() === 'POST');
  await panel.getByRole('button', { name: '保存新说明', exact: true }).click();
  const descriptionSaved = await descriptionResponse;
  assert(descriptionSaved.status() === 201, `Normal UI must save the new explanation and exact mapping: ${descriptionSaved.status()} ${await descriptionSaved.text()}`);
  const firstDescription = (await descriptionSaved.json()).record;
  assert(firstDescription.observation.totalRows === null && firstDescription.observation.scannedRows === null, 'Blank observation counts remain unknown');
  assert(firstDescription.statements[0].confirmed === false, 'Saving an explanation cannot confirm it');
  assert(firstDescription.mappings[0].conceptRefs[0].revisionId === conceptRef.revisionId, 'Mapping pins the selected exact concept revision');
  await panel.getByRole('checkbox', { name: '本次确认此解释', exact: true }).check();
  await panel.getByRole('checkbox', { name: '本次确认此映射', exact: true }).check();
  assert(await panel.getByRole('textbox', { name: /^本次确认标签/ }).inputValue() === '', 'Optional personal confirmation label deliberately remains blank');
  const confirmationResponse = page.waitForResponse(response => response.url().endsWith(`/api/projects/${projectId}/data-context/descriptions`) && response.request().method() === 'POST');
  await panel.getByRole('button', { name: '确认所选条目', exact: true }).click();
  const confirmationSaved = await confirmationResponse;
  assert(confirmationSaved.status() === 201, `Confirmation adds a separate description revision: ${confirmationSaved.status()} ${await confirmationSaved.text()}`);
  const confirmedDescription = (await confirmationSaved.json()).record;
  assert(confirmedDescription.descriptionRevisionId !== firstDescription.descriptionRevisionId && confirmedDescription.statements[0].confirmed, 'Explicit item confirmation preserves the unconfirmed original revision');
  assert(confirmedDescription.statements[0].confirmedBy === 'user' && confirmedDescription.mappings[0].confirmedBy === 'user', 'Leaving the optional label blank records this explicit user confirmation');
  const prepareResponse = page.waitForResponse(response => response.url().endsWith(`/api/projects/${projectId}/data-context/prepare`) && response.request().method() === 'POST');
  await panel.getByRole('button', { name: '用于本轮', exact: true }).click();
  assert((await prepareResponse).status() === 200, 'Prepare an analysis copy only on explicit selection');
  await page.locator('summary').filter({ hasText: '本轮项目数据 · 1 项' }).waitFor();
  assert((await metrics()).requestCount === before + 1, 'Saving/confirming/preparing data cannot dispatch a model');
  await panel.getByRole('button', { name: '关闭数据说明与来源', exact: true }).click();
  await message.fill('M2_UI_APPEND：继续原任务，明确使用本轮固定说明。');
  const sentResponse = page.waitForResponse(response => response.url().endsWith(`/api/projects/${projectId}/tasks/${taskId}/messages`) && response.request().method() === 'POST');
  await message.press('Enter');
  const accepted = await sentResponse;
  assert(accepted.status() === 202, 'The original task accepts the selected data through its existing message endpoint');
  const selected = accepted.request().postDataJSON().projectData;
  assert(selected.length === 1 && selected[0].descriptionRevisionId === confirmedDescription.descriptionRevisionId, 'The normal composer sends the confirmed exact revision');
  const sentRequestId = accepted.request().postDataJSON().requestId;
  const deadline = Date.now() + 15000;
  while ((await api(`/api/projects/${projectId}/tasks/${taskId}`)).task.lastRun?.id !== sentRequestId ||
    (await api(`/api/projects/${projectId}/tasks/${taskId}`)).task.lastRun?.status !== 'completed') {
    assert(Date.now() < deadline, 'The selected-data UI turn must complete'); await page.waitForTimeout(20);
  }
  const afterSend = await metrics();
  assert(afterSend.requestCount === before + 2, 'The appended same-task message makes one synthetic request');
  assert(JSON.stringify(afterSend.requests.at(-1).messages).includes('M2_UI_ROW_MEANING'), 'The actual request receives the saved explanation');
  const receipts = await api(`/api/projects/${projectId}/tasks/${taskId}/context-receipts`);
  assert(receipts.receipts.some(value => value.providedContext?.projectData?.some(item => item.selection.descriptionRevisionId === confirmedDescription.descriptionRevisionId)), 'Native receipt keeps the precise selection');
  checks.push('Separate explanation save and item confirmation, exact concept mapping, explicit same-task selection and native request receipt');
  const reportResponse = page.waitForResponse(response => response.url().endsWith(`/api/projects/${projectId}/files/save-report`) && response.request().method() === 'POST');
  await page.getByRole('button', { name: '将最新回复保存为最终报告', exact: true }).click();
  const reportSaved = await reportResponse;
  assert(reportSaved.status() === 201, 'Saving the user-selected final reply must preserve the existing report entrypoint');
  const reportFile = (await reportSaved.json()).file;
  const reportsFolder = files.locator('.project-file-tree > details').filter({ has: page.locator('summary code').filter({ hasText: '060_reports' }) });
  if (await reportsFolder.getAttribute('open') === null) await reportsFolder.locator('summary').first().click();
  await files.getByRole('button', { name: `记录此稿来源 ${reportFile.path.split('/').at(-1)}`, exact: true }).click();
  await panel.getByRole('heading', { name: '数据说明与来源', exact: true }).waitFor();
  const sourceCheckbox = panel.getByRole('checkbox', { name: `说明 ${confirmedDescription.descriptionRevisionId.slice(0, 8)}`, exact: true });
  assert(!await sourceCheckbox.isChecked(), 'Provided context is not automatically promoted to declared adoption');
  await sourceCheckbox.check();
  await panel.locator('summary').filter({ hasText: '计算 / 代码附件' }).click();
  await panel.getByRole('checkbox', { name: /^020_clean\/m2-sales\.csv/ }).check();
  await panel.getByLabel('来源声明', { exact: true }).fill('M2_UI_CITATION：用户显式声明当前稿来源，固定回复不代表真实分析正确。');
  const citationResponse = page.waitForResponse(response => response.url().endsWith(`/api/projects/${projectId}/data-context/citations`) && response.request().method() === 'POST');
  await panel.getByRole('button', { name: '记录此稿来源', exact: true }).click();
  const citationSaved = await citationResponse;
  assert(citationSaved.status() === 201, 'User-recorded provenance creates a distinct fixed citation');
  const citation = (await citationSaved.json()).record;
  assert(citation.sourcesDeclared && citation.selections[0].descriptionRevisionId === confirmedDescription.descriptionRevisionId, 'Citation records only the exact user-selected source');
  assert(citation.attachments.length === 1 && citation.attachments[0].originalPath === '020_clean/m2-sales.csv', 'Only explicitly checked evidence files are fixed');
  await panel.getByRole('button', { name: '读取固定报告', exact: true }).click();
  assert((await panel.locator('pre').innerText()).includes('SDK 合成回复'), 'The fixed report is readable through normal history UI');
  await panel.screenshot({ path: 'output/playwright/m2/data-context-success-wide.png' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Wide data panel has no document overflow');
  const beforeReload = (await metrics()).requestCount;
  await page.reload();
  await page.getByRole('heading', { name: taskName, exact: true, level: 1 }).waitFor();
  const historical = await api(`/api/projects/${projectId}/data-context/citations/${citation.citationId}`);
  assert(historical.record.report.sha256 === citation.report.sha256, 'Reload preserves fixed report identity');
  assert((await metrics()).requestCount === beforeReload, 'History/reload cannot replay a model');
  await page.setViewportSize({ width: 390, height: 844 });
  const showFiles = page.getByRole('button', { name: '展开项目文件', exact: true });
  await showFiles.click();
  await files.getByRole('button', { name: '数据说明与来源 m2-sales.csv', exact: true }).click();
  await panel.getByRole('button', { name: '读取固定内容', exact: true }).click();
  await panel.getByRole('heading', { name: '固定输入内容', exact: true }).waitFor();
  assert((await panel.locator('pre').innerText()).includes('synthetic-b,20'), 'Narrow UI can reopen the preserved exact input');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '390px data panel has no document overflow');
  await page.screenshot({ path: 'output/playwright/m2/data-context-success-narrow.png' });
  await page.setViewportSize({ width: 320, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '320px data panel has no document overflow');
  await page.screenshot({ path: 'output/playwright/m2/data-context-success-320.png' });
  checks.push('Explicit report-source selection and fixed readback; reload without replay; 1440/390/320px panel paths');
  const detail = await api(`/api/projects/${projectId}/tasks/${taskId}`);
  assert(detail.task.id === taskId && detail.project.tasks.length === 1, 'Adding a data explanation must keep the original task');
  assert(errors.length === 0, `Browser errors: ${errors.join(', ')}`);
  assert(outbound.length === 0, `Non-loopback requests: ${outbound.join(', ')}`);
  return { result: 'PASS', checks, projectId, taskId, providerRequestCount: (await metrics()).requestCount };
}
