async (page) => {
  const initial = new URL(page.url());
  const baseUrl = initial.origin, providerUrl = initial.searchParams.get('provider');
  if (initial.port !== '4183' || !providerUrl || new URL(providerUrl).hostname !== '127.0.0.1') throw new Error('Use isolated QA UI 4183 with the synthetic provider query parameter.');
  const checks = [], outbound = [], errors = [];
  page.on('request', request => { if (new URL(request.url()).hostname !== '127.0.0.1') outbound.push(request.url()); });
  page.on('pageerror', error => errors.push(error.message));
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const headers = { origin: baseUrl, 'x-optracall-client': '1' };
  const metrics = async () => (await page.request.get(new URL('/__qa', providerUrl).href)).json();
  const status = text => page.getByRole('status').filter({ hasText: text });
  const secret = 'synthetic-browser-runtime-key';
  await page.request.delete(baseUrl + '/api/configuration', { headers });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(baseUrl);
  await page.getByRole('button', { name: '模型设置', exact: true }).click();
  await page.getByRole('button', { name: '保存配置', exact: true }).waitFor();
  const before = (await metrics()).requestCount;
  await page.getByRole('textbox', { name: /配置名称/ }).fill('本地合成协议验证');
  await page.getByRole('textbox', { name: /服务地址/ }).fill(providerUrl);
  await page.getByRole('textbox', { name: /模型名称/ }).fill('synthetic-model');
  await page.getByLabel(/API Key/).fill(secret);
  assert(await page.getByRole('button', { name: '测试连接', exact: true }).isDisabled(), 'Unsaved fields cannot trigger a test');
  await page.getByRole('button', { name: '保存配置', exact: true }).click(); await status('配置已保存到 Host 内存').waitFor();
  assert(await page.getByLabel(/API Key/).inputValue() === '', 'Saved key must clear from form');
  assert((await metrics()).requestCount === before, 'Save must not automatically call the provider');
  const readback = await page.request.get(baseUrl + '/api/configuration', { headers });
  assert(!(await readback.text()).includes(secret), 'Key must not be read back over HTTP');
  await page.reload();
  await page.getByRole('button', { name: '模型设置', exact: true }).click();
  await page.getByRole('textbox', { name: /配置名称/ }).waitFor();
  await page.waitForFunction(() => document.querySelector('#config-name')?.value === '本地合成协议验证');
  assert(await page.getByLabel(/API Key/).inputValue() === '', 'Reload recovers public config without key');
  assert((await metrics()).requestCount === before, 'Read/reload must not automatically call the provider');
  checks.push('Editable LLM settings, Host-memory save, masked readback, cleared input, refresh without key or model call');
  await page.getByRole('button', { name: '返回项目空间', exact: true }).click();
  await page.getByRole('button', { name: '新建项目', exact: true }).click();
  await page.getByRole('textbox', { name: '项目名称', exact: true }).fill('不可发送的项目名称');
  await page.getByRole('button', { name: '创建项目', exact: true }).click();
  await page.getByRole('textbox', { name: '消息', exact: true }).fill('不可发送的项目草稿');
  await page.getByRole('button', { name: '模型设置', exact: true }).click();
  await page.getByRole('button', { name: '测试连接', exact: true }).click(); await status('已通过统一 SDK 收到固定短句回复').waitFor();
  const success = await metrics();
  assert(success.requestCount === before + 1, 'One explicit click must issue exactly one model request');
  const material = JSON.stringify(success.requests.at(-1).messages);
  assert(material.includes('请仅回复 OK。') && !material.includes('不可发送的项目'), 'Test must send fixed prompt without project content');
  checks.push('Explicit success through actual SDK and synthetic HTTP; no project data');
  await page.getByRole('textbox', { name: /服务地址/ }).fill(new URL('/failure/v1', providerUrl).href);
  assert(await page.getByRole('button', { name: '测试连接', exact: true }).isDisabled(), 'Changed endpoint needs a saved config');
  await page.getByRole('button', { name: '保存配置', exact: true }).click();
  await page.getByRole('alert').waitFor();
  assert(await page.getByLabel(/API Key/).getAttribute('aria-invalid') === 'true', 'New endpoint must require a fresh key');
  await page.getByLabel(/API Key/).fill(secret);
  await page.getByRole('button', { name: '保存配置', exact: true }).click(); await status('配置已保存到 Host 内存').waitFor();
  await page.getByRole('button', { name: '测试连接', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '连接测试未完成' }).waitFor();
  assert(!(await page.locator('body').textContent()).includes(secret), 'Provider error must not reveal key');
  assert(!(await page.locator('body').textContent()).includes('synthetic-private-detail'), 'Provider raw error must not be shown');
  assert((await metrics()).requestCount === before + 2, 'Failure must not trigger automatic retries');
  checks.push('Endpoint change requires key, and provider failure is safe and has no automatic retry');
  await page.getByRole('textbox', { name: /服务地址/ }).fill(new URL('/slow/v1', providerUrl).href);
  await page.getByLabel(/API Key/).fill(secret);
  await page.getByRole('button', { name: '保存配置', exact: true }).click(); await status('配置已保存到 Host 内存').waitFor();
  await page.getByRole('button', { name: '测试连接', exact: true }).click();
  await page.getByRole('button', { name: '取消测试', exact: true }).waitFor();
  for (let i = 0; i < 100 && (await metrics()).requestCount < before + 3; i++) await new Promise(resolve => setTimeout(resolve, 10));
  await page.getByRole('button', { name: '取消测试', exact: true }).click(); await status('连接测试已取消').waitFor();
  for (let i = 0; i < 100 && !(await metrics()).requests.at(-1)?.closedEarly; i++) await new Promise(resolve => setTimeout(resolve, 10));
  assert((await metrics()).requests.at(-1).closedEarly, 'Cancel must actually abort the SDK provider stream');
  await page.getByRole('button', { name: '清除配置', exact: true }).click(); await status('配置已清除').waitFor();
  assert(await page.getByRole('button', { name: '测试连接', exact: true }).isDisabled(), 'Cleared config must be disconnected');
  assert((await (await page.request.get(baseUrl + '/api/configuration', { headers })).json()).configuration === null, 'Host memory must be cleared');
  checks.push('User cancellation aborts actual SDK stream, and clear removes Host config');
  await page.getByRole('button', { name: '切换为深色', exact: true }).click();
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await page.getByRole('button', { name: '展开侧栏', exact: true }).waitFor();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Narrow LLM form must not overflow');
    await page.getByLabel(/API Key/).fill('synthetic-narrow-key');
    assert(await page.getByLabel(/API Key/).isVisible(), 'Editable key must remain reachable on narrow screen');
  }
  assert(await page.evaluate(() => localStorage.length === 0 && sessionStorage.length === 0), 'No browser storage persistence');
  assert(outbound.length === 0, 'No external provider requests from browser test: ' + outbound.join(','));
  assert(errors.length === 0, 'No browser errors: ' + errors.join(','));
  checks.push('390/320px dark settings, no horizontal overflow, no web storage or browser errors');
  await page.setViewportSize({ width: 1440, height: 900 });
  return { result: 'PASS', checks, syntheticRequests: (await metrics()).requestCount - before, externalRequests: outbound.length, browserErrors: errors.length };
}
