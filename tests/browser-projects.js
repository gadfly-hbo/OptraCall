async (page) => {
  const baseUrl = new URL(page.url()).origin;
  const checks = [], outbound = [], errors = [];
  const assert = (value, message) => { if (!value) throw new Error(message); };
  page.on('request', request => { if (new URL(request.url()).hostname !== '127.0.0.1') outbound.push(request.url()); });
  page.on('pageerror', error => errors.push(error.message));
  const projectList = () => page.getByRole('navigation', { name: '项目空间列表' });
  const files = () => page.getByRole('complementary', { name: '项目文件', exact: true });
  const mode = name => page.getByRole('group', { name: '工作区切换' }).getByRole('button', { name, exact: true });
  const create = async name => {
    await page.getByRole('button', { name: '新建项目', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '新建项目', exact: true });
    await dialog.getByRole('textbox', { name: '项目名称', exact: true }).fill(name);
    await dialog.getByRole('button', { name: '创建项目', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    await page.getByRole('heading', { name, level: 1, exact: true }).waitFor();
  };
  const narrow = async width => {
    await page.setViewportSize({ width, height: 844 });
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  };
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(baseUrl);
  await page.getByRole('heading', { name: '从一个项目开始', exact: true }).waitFor();
  assert(await page.getByRole('textbox', { name: '消息', exact: true }).count() === 0, 'No project means no standalone chat composer');
  assert(await page.getByRole('button', { name: /新建会话|新会话|新建对话/ }).count() === 0, 'Standalone conversation creation must be absent');
  const trigger = page.getByRole('button', { name: '新建项目', exact: true });
  await trigger.click();
  const dialog = page.getByRole('dialog', { name: '新建项目', exact: true });
  assert(await dialog.getByRole('textbox', { name: '项目名称', exact: true }).evaluate(element => element === document.activeElement), 'Name receives initial focus');
  await dialog.getByRole('textbox', { name: '项目名称', exact: true }).fill('   ');
  await dialog.getByRole('button', { name: '创建项目', exact: true }).click();
  await dialog.getByRole('alert').waitFor();
  assert(await projectList().getByRole('button').count() === 0, 'Invalid name must not create a phantom project');
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' });
  assert(await trigger.evaluate(element => element === document.activeElement), 'Cancel restores creating trigger focus');
  checks.push('No standalone chat, empty-name validation, cancel without phantom project and modal focus return');
  await create('十月经营复盘');
  assert(await projectList().getByRole('button', { name: '十月经营复盘', exact: true }).isVisible(), 'Named project is immediately reachable');
  await files().waitFor();
  const summaries = await files().locator('summary code').allTextContents();
  assert(JSON.stringify(summaries) === JSON.stringify(['010_draw', '020_clean', '060_reports']), 'Default folder spellings and order must match user exactly');
  await files().locator('summary').filter({ hasText: '010_draw' }).click();
  assert(await files().locator('details').filter({ has: page.locator('summary').filter({ hasText: '010_draw' }) }).getByText('空文件夹 · 尚无文件', { exact: true }).isVisible(), 'Folder can expand to an honest empty state');
  assert(await files().getByText('虚拟文件夹 · 未写入本地磁盘', { exact: true }).isVisible(), 'Virtual folder scope disclosed');
  await files().getByRole('button', { name: '关闭项目文件栏', exact: true }).click();
  await files().waitFor({ state: 'detached' });
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '展开项目文件');
  assert(await page.getByRole('button', { name: '展开项目文件', exact: true }).evaluate(element => element === document.activeElement), 'Closing files restores header toggle focus');
  await page.getByRole('button', { name: '展开项目文件', exact: true }).click(); await files().waitFor();
  await page.getByRole('button', { name: '收起项目文件', exact: true }).click();
  checks.push('Named project, exact default folders, expandable empty folder and reversible file panel');
  const input = page.getByRole('textbox', { name: '消息', exact: true });
  await input.fill('项目 A 的第一句话'); await input.press('Enter');
  await input.fill('项目 A 下一句');
  await trigger.click(); await dialog.waitFor(); await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'detached' });
  assert(await page.getByRole('button', { name: '停止生成', exact: true }).isVisible(), 'Escape in creation dialog must not cancel running project');
  await create('会员营销评估');
  assert(await files().getByText('会员营销评估', { exact: true }).isVisible(), 'File panel follows active project');
  assert(await input.inputValue() === '', 'Second project has its own draft');
  assert(await page.locator('.message').count() === 0, 'Second project has no messages from first');
  await input.fill('项目 B 草稿');
  const first = projectList().getByRole('button', { name: '十月经营复盘', exact: true });
  await first.locator('.running-dot').waitFor({ state: 'detached' });
  await first.click();
  assert(await input.inputValue() === '项目 A 下一句', 'Switching projects restores project draft');
  await page.getByRole('status').filter({ hasText: '演示回复已完成' }).waitFor();
  assert(await page.locator('.topbar-title').textContent() === '十月经营复盘', 'Project heading remains named after its first prompt');
  assert(await first.isVisible(), 'Project name remains stable after its first prompt');
  assert(await files().getByText('十月经营复盘', { exact: true }).isVisible(), 'Files return to selected project');
  await page.getByRole('button', { name: '项目空间 (2)', exact: true }).click();
  assert(!await projectList().isVisible(), 'Project list can collapse');
  await page.getByRole('button', { name: '项目空间 (2)', exact: true }).click();
  checks.push('Project identity, draft isolation, hidden response completion and creation-dialog Escape isolation');
  await mode('决策').click(); await mode('分析').click();
  assert(await input.inputValue() === '项目 A 下一句', 'Workspace switch preserves project draft');
  for (const width of [390, 320]) {
    await narrow(width);
    const expectedDraft = width === 390 ? '项目 A 下一句' : '项目 B 草稿';
    await page.getByRole('button', { name: '展开项目文件', exact: true }).click();
    await files().waitFor();
    assert(!await input.isVisible(), 'Narrow file pane has its own view without squeezing the composer');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Narrow file view must not overflow');
    await files().locator('summary').filter({ hasText: '060_reports' }).click();
    await files().getByRole('button', { name: '关闭项目文件栏', exact: true }).click();
    await input.waitFor({ state: 'visible' });
    assert(await input.inputValue() === expectedDraft, 'Closing narrow files restores original project');
    const toggle = page.getByRole('button', { name: '展开项目文件', exact: true });
    assert(await toggle.evaluate(element => { const r = element.getBoundingClientRect(); return element.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)); }), 'Narrow file toggle must receive pointer hits');
    await page.getByRole('button', { name: '展开侧栏', exact: true }).click();
    await projectList().getByRole('button', { name: '会员营销评估', exact: true }).click();
    assert(await input.inputValue() === '项目 B 草稿', 'Narrow project navigation remains usable');
    await page.getByRole('button', { name: width === 390 ? '切换为深色' : '切换为浅色', exact: true }).click();
  }
  checks.push('390/320px light/dark file toggles, project navigation and preserved drafts');
  assert(outbound.length === 0, 'No remote, file or model requests: ' + outbound.join(','));
  assert(errors.length === 0, 'No browser exceptions: ' + errors.join(','));
  assert(await page.evaluate(() => localStorage.length === 0 && sessionStorage.length === 0), 'No persistent demo storage');
  await page.reload();
  await page.getByRole('heading', { name: '从一个项目开始', exact: true }).waitFor();
  assert(await page.getByRole('textbox', { name: '消息', exact: true }).count() === 0, 'Reload clears virtual projects as disclosed');
  await page.setViewportSize({ width: 1440, height: 900 });
  return { result: 'PASS', checks, externalRequests: outbound.length, browserErrors: errors.length };
}
