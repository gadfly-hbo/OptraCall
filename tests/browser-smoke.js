async (page) => {
  const baseUrl = new URL(page.url()).origin;
  if (new URL(baseUrl).port !== '4183') throw new Error('Use the isolated QA UI on port 4183; this test changes Host configuration.');
  await page.request.delete(baseUrl + '/api/configuration', { headers: { origin: baseUrl, 'x-optracall-client': '1' } });
  const passed = [];
  const outbound = [];
  const errors = [];
  const consoleErrors = [];
  page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()); });
  page.on('request', request => { if (new URL(request.url()).hostname !== '127.0.0.1') outbound.push(request.url()); });
  page.on('pageerror', error => errors.push(error.message));
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const status = text => page.getByRole('status').filter({ hasText: text });
  const createProject = async name => {
    await page.getByRole('button', { name: '新建项目', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '新建项目', exact: true });
    await dialog.getByRole('textbox', { name: '项目名称', exact: true }).fill(name);
    await dialog.getByRole('button', { name: '创建项目', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    await page.getByRole('heading', { name, exact: true, level: 1 }).waitFor();
  };
  let stage = 'initial desktop setup';
  try {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(baseUrl);
  await page.getByRole('complementary', { name: '工作台导航' }).waitFor();
  await page.getByRole('heading', { name: '从一个项目开始' }).waitFor();
  await createProject('项目 A');
  assert(await page.getByRole('button', { name: '发送消息', exact: true }).isDisabled(), 'Empty send must be disabled');
  await page.getByRole('button', { name: '模型设置', exact: true }).click();
  await page.getByRole('textbox', { name: /配置名称/ }).fill('');
  await page.getByRole('textbox', { name: /服务地址/ }).fill('');
  await page.getByRole('textbox', { name: /模型名称/ }).fill('');
  await page.getByRole('button', { name: '保存配置', exact: true }).click();
  await page.getByRole('alert').waitFor();
  assert(await page.getByRole('textbox', { name: /配置名称/ }).getAttribute('aria-invalid') === 'true', 'Field error must be associated');
  assert(await page.getByLabel(/API Key/).getAttribute('readonly') === null, 'Stage3 key input must be editable');
  assert(await page.getByRole('button', { name: '测试连接', exact: true }).isDisabled(), 'No fake connection test');
  await page.getByRole('button', { name: '填入示例', exact: true }).click();
  await page.getByRole('textbox', { name: /模型名称/ }).fill('custom-demo');
  await page.getByLabel(/API Key/).fill('synthetic-browser-key');
  await page.getByRole('button', { name: '保存配置', exact: true }).click();
  await status('配置已保存到 Host 内存').waitFor();
  assert(await page.getByLabel(/API Key/).inputValue() === '', 'Saved key must clear from UI');
  passed.push('LLM validation, editable memory-only key, cleared input and no automatic model test');
  await page.getByRole('button', { name: '返回项目空间', exact: true }).click();
  await page.getByRole('button', { name: '演示模型 ⌄', exact: true }).click();
  await page.getByRole('button', { name: '返回项目空间', exact: true }).click();
  await page.waitForFunction(() => document.activeElement?.classList.contains('model-button'));
  passed.push('Settings return focus and existing conversation model snapshot');
  let input = page.getByRole('textbox', { name: '消息', exact: true });
  await input.fill('第一行'); await input.press('Shift+Enter');
  assert((await input.inputValue()).includes('\n'), 'Shift+Enter must insert newline');
  await input.fill('中文输入法测试');
  await input.dispatchEvent('compositionstart');
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', keyCode: 229, isComposing: true, bubbles: true });
  assert(await page.locator('.message.user').count() === 0, 'IME Enter must not send');
  await input.dispatchEvent('compositionend');
  passed.push('Chinese composition and multiline input');
  await input.fill('未发送草稿 A');
  await createProject('项目 B');
  await page.getByRole('navigation', { name: '项目空间列表' }).getByRole('button', { name: '项目 A', exact: true }).click();
  input = page.getByRole('textbox', { name: '消息', exact: true });
  assert(await input.inputValue() === '未发送草稿 A', 'Unsent draft must remain reachable after new conversation');
  passed.push('Unsent draft recovery through project space');
  await input.fill('会话 A'); await input.press('Enter');
  await page.waitForFunction(() => (document.querySelector('.message.assistant .message-content')?.textContent?.length ?? 0) > 8);
  await input.fill('停止后保留的草稿');
  await page.getByRole('button', { name: '停止生成', exact: true }).click();
  await status('已停止，部分回复已保留').waitFor();
  assert((await page.locator('.message.assistant .message-content').textContent()).length > 0, 'Partial output must remain');
  assert(await input.inputValue() === '停止后保留的草稿', 'Stop must preserve draft');
  passed.push('Streaming, cancellation acknowledgement, partial output and draft');
  await createProject('项目 C');
  assert(await page.getByRole('button', { name: 'custom-demo ⌄', exact: true }).isVisible(), 'New conversation must use new config');
  input = page.getByRole('textbox', { name: '消息', exact: true });
  await input.fill('会话 B'); await input.press('Enter');
  await createProject('项目 D');
  await page.getByRole('heading', { name: '项目 D', exact: true, level: 1 }).waitFor();
  const historyB = page.getByRole('navigation', { name: '项目空间列表' }).getByRole('button', { name: '项目 C', exact: true });
  await historyB.locator('.running-dot').waitFor({ state: 'detached' });
  assert(await page.locator('.message').count() === 0, 'Background events must not enter new conversation');
  await historyB.click(); await status('演示回复已完成').waitFor();
  assert(await page.locator('.message.user .message-content').textContent() === '会话 B', 'Conversation must retain its own user text');
  passed.push('New project model snapshot and background event isolation');
  await page.getByRole('combobox', { name: '演示场景', exact: true }).selectOption('failure');
  input = page.getByRole('textbox', { name: '消息', exact: true });
  await input.fill('失败测试'); await input.press('Enter');
  await page.getByRole('alert').waitFor();
  assert(await page.getByText('此条演示回复未完成', { exact: true }).count() === 1, 'Failed reply must retain its outcome');
  await input.fill('重试时保留的下一句');
  await page.getByRole('button', { name: '重试演示', exact: true }).click();
  await status('演示回复已完成').waitFor();
  assert(await page.getByText('此条演示回复未完成', { exact: true }).count() === 1, 'Retry must not erase historical failure');
  assert(await input.inputValue() === '重试时保留的下一句', 'Retry must preserve a separately written draft');
  passed.push('Failure, explicit retry and retained failure marker');
  await page.getByRole('button', { name: '切换为深色', exact: true }).click();
  assert(await page.locator('.app').getAttribute('data-theme') === 'dark', 'Dark theme must apply');
  await page.getByRole('button', { name: '切换为浅色', exact: true }).click();
  stage = 'narrow navigation and settings';
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '展开侧栏', exact: true }).waitFor();
  assert(await page.getByRole('button', { name: '展开侧栏', exact: true }).isVisible(), 'Narrow sidebar must collapse');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Narrow page must not overflow');
  await page.getByRole('button', { name: '展开侧栏', exact: true }).click();
  await page.getByRole('complementary', { name: '工作台导航' }).waitFor();
  await page.getByRole('button', { name: '模型设置', exact: true }).click();
  await page.getByRole('heading', { name: '模型配置', exact: true }).waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Narrow settings must not overflow');
  passed.push('Light/dark parity and narrow chat/settings');
  assert(await page.evaluate(() => localStorage.length === 0 && sessionStorage.length === 0), 'Demo must not persist configuration or key in web storage');
  assert(outbound.length === 0, 'Demo must not make external/model requests: ' + outbound.join(','));
  assert(consoleErrors.length === 0, 'Console errors: ' + consoleErrors.join(','));
  assert(errors.length === 0, 'Browser must have no uncaught errors: ' + errors.join(','));
  passed.push('No web-storage persistence, external requests or uncaught errors');
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('button', { name: '返回项目空间', exact: true }).click();
  return { result: 'PASS', checks: passed, externalRequests: outbound.length, uncaughtErrors: errors.length };
  } catch (error) {
    const context = await page.evaluate(() => ({ width: innerWidth, sidebar: Boolean(document.getElementById('sidebar')), title: document.querySelector('h1')?.textContent }));
    throw new Error(stage + ': ' + error.message + '; context=' + JSON.stringify(context) + '; passed=' + passed.join(' / '));
  }
}
