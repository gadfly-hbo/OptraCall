async (page) => {
  const initial = new URL(page.url());
  const baseUrl = initial.origin, providerUrl = initial.searchParams.get('provider');
  if (initial.port !== '4183' || !providerUrl || new URL(providerUrl).hostname !== '127.0.0.1') throw new Error('Use isolated QA UI 4183 and the synthetic provider query parameter.');
  const passed = [], outbound = [], errors = [];
  page.on('request', request => { if (new URL(request.url()).hostname !== '127.0.0.1') outbound.push(request.url()); });
  page.on('pageerror', error => errors.push(error.message));
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const mode = name => page.getByRole('group', { name: '工作区切换' }).getByRole('button', { name, exact: true });
  const category = name => page.getByRole('navigation', { name: '能力目录' }).getByRole('button', { name, exact: true });
  const title = name => page.getByRole('heading', { name, exact: true, level: 1 });
  const noOverflow = async () => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Page must not overflow horizontally');
  const createProject = async name => {
    await page.getByRole('button', { name: '新建项目', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '新建项目', exact: true });
    await dialog.getByRole('textbox', { name: '项目名称', exact: true }).fill(name);
    await dialog.getByRole('button', { name: '创建项目', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    await page.getByRole('heading', { name, exact: true, level: 1 }).waitFor();
  };
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(baseUrl);
  const headers = { origin: baseUrl, 'x-optracall-client': '1' };
  const configured = await (await page.request.put(baseUrl + '/api/configuration', { headers, data: { name: '目录切换合成模型', provider: 'openai-compatible', api: 'openai-completions', baseUrl: new URL('/slow/v1', providerUrl).href, model: 'synthetic-model', apiKey: 'synthetic-catalog-key' } })).json();
  assert(configured.configuration?.id, 'Synthetic fixture configuration must save');
  await page.request.post(baseUrl + '/api/configuration/select', { headers, data: { id: configured.configuration.id } });
  await page.reload();
  await page.getByRole('button', { name: '新建项目', exact: true }).waitFor();
  await createProject('目录回归项目 ' + Date.now());
  await page.getByRole('textbox', { name: '消息', exact: true }).fill('页面切换保留的草稿');
  for (const name of ['分析资产', '场景组合', '连接器', '业务插件']) {
    await category(name).click(); await title(name).waitFor();
    assert(await category(name).getAttribute('aria-current') === 'page', 'Sidebar selection must match category');
    assert(await page.getByRole('group', { name: '能力目录分类' }).getByRole('button', { name, exact: true }).getAttribute('aria-pressed') === 'true', 'Directory selection must match sidebar');
    assert(await page.locator('.catalog-card').count() >= 3, 'Each category needs distinct placeholder examples');
    assert(await page.getByText('演示目录 · 未接入', { exact: true }).isVisible(), 'Directory must disclose placeholder status');
  }
  passed.push('All four sidebar directories, category synchronization and honest placeholder status');
  await page.getByRole('group', { name: '能力目录分类' }).getByRole('button', { name: '分析资产', exact: true }).click();
  const search = page.getByRole('textbox', { name: '搜索分析资产', exact: true });
  await search.fill('  COHORT  ');
  assert(await page.locator('.catalog-card').count() === 1, 'Search must match case-insensitively');
  await page.getByRole('combobox', { name: '业务标签', exact: true }).selectOption('指标口径');
  await page.getByRole('heading', { name: '没有找到匹配的示例' }).waitFor();
  await page.getByRole('button', { name: '清除筛选', exact: true }).click();
  assert(await search.inputValue() === '', 'Clear resets query');
  assert(await page.locator('.catalog-card').count() === 5, 'Clear restores category examples');
  const detailTrigger = page.getByRole('button', { name: '查看分析方法资产包规划', exact: true });
  await detailTrigger.click();
  const dialog = page.getByRole('dialog', { name: '分析方法资产包', exact: true });
  await dialog.waitFor();
  assert(await dialog.getByText('规划示例 · 未接入', { exact: true }).isVisible(), 'Detail must disclose not integrated');
  assert(await page.evaluate(() => document.querySelector('dialog')?.contains(document.activeElement)), 'Focus must enter modal');
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' });
  assert(await detailTrigger.evaluate(element => element === document.activeElement), 'Escape must return focus to card trigger');
  await detailTrigger.click(); await page.getByRole('button', { name: '关闭详情', exact: true }).click();
  passed.push('Search, combined filters, empty reset, modal close and keyboard focus return');
  await category('业务插件').click();
  await page.getByRole('button', { name: '查看决策工作台规划', exact: true }).click();
  assert(await page.getByRole('dialog', { name: '决策工作台', exact: true }).getByText('预留接入 · 未接入', { exact: true }).isVisible(), 'Decision plugin must be reserved');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '返回工作区 →', exact: true }).click();
  assert(await page.getByRole('textbox', { name: '消息', exact: true }).inputValue() === '页面切换保留的草稿', 'Directory return must preserve draft');
  await mode('决策').click(); await title('决策工作台').waitFor();
  assert(await mode('决策').getAttribute('aria-pressed') === 'true', 'Decision mode must be selected');
  assert(await page.getByText('decision-platform 接入预留', { exact: true }).isVisible(), 'Decision integration boundary visible');
  assert(await page.locator('.decision-card').count() === 4, 'Decision placeholder board exists');
  assert(await page.locator('.decision-page button').count() === 0, 'Placeholder must have no real business actions');
  await category('场景组合').click();
  await page.getByRole('button', { name: '返回工作区 →', exact: true }).click(); await title('决策工作台').waitFor();
  await page.getByRole('button', { name: '模型设置', exact: true }).click();
  await page.getByRole('button', { name: '返回决策工作台', exact: true }).click(); await title('决策工作台').waitFor();
  await category('连接器').click();
  await page.getByRole('button', { name: '模型设置', exact: true }).click();
  await page.getByRole('button', { name: '返回连接器', exact: true }).click(); await title('连接器').waitFor();
  passed.push('Decision reserved board, last workspace return and settings return from both new views');
  await mode('分析').click();
  const input = page.getByRole('textbox', { name: '消息', exact: true });
  assert(await input.inputValue() === '页面切换保留的草稿', 'Decision switching must preserve draft');
  await input.fill('跨页面真实回复'); await page.waitForFunction(() => document.querySelector('.send-button')?.disabled === false); await input.press('Enter');
  await page.waitForFunction(() => (document.querySelector('.message.assistant .message-content')?.textContent?.length ?? 0) > 0);
  await input.fill('回复期间的新草稿'); await mode('决策').click(); await category('分析资产').click(); await mode('分析').click();
  assert(await page.getByRole('button', { name: '停止生成', exact: true }).isVisible(), 'Native slow run must remain active after view switching');
  await page.getByRole('button', { name: '停止生成', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '已停止，已保存的部分输出仍保留' }).waitFor();
  assert(await input.inputValue() === '回复期间的新草稿', 'In-flight switching must preserve next draft');
  assert(await page.locator('.message.user .message-content').textContent() === '跨页面真实回复', 'Switch must preserve conversation');
  passed.push('Analysis/decision/catalog switching preserves drafts and the in-flight native response; explicit stop retains partial text');
  await page.getByRole('button', { name: '切换为深色', exact: true }).click();
  await mode('决策').click(); await noOverflow();
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await page.getByRole('button', { name: '展开侧栏', exact: true }).waitFor();
    assert(await mode('分析').isVisible() && await mode('决策').isVisible(), 'Mode switch remains visible on narrow screen');
    assert(await page.evaluate(() => document.querySelector('.workspace-switch').getBoundingClientRect().bottom <= document.querySelector('.topbar').getBoundingClientRect().bottom), 'Mode switch must stay within the header above content');
    await noOverflow();
    await page.getByRole('button', { name: '展开侧栏', exact: true }).click();
    await category('业务插件').click(); await title('业务插件').waitFor(); await noOverflow();
    await page.getByRole('button', { name: '查看决策工作台规划', exact: true }).click();
    await noOverflow(); await page.keyboard.press('Escape');
    await mode('分析').click(); await noOverflow();
    assert(await input.inputValue() === '回复期间的新草稿', 'Narrow navigation preserves draft');
    await mode('决策').click();
  }
  passed.push('Dark theme and 390/320px decision, catalog, modal and original conversation without horizontal overflow');
  assert(outbound.length === 0, 'No external browser requests: ' + outbound.join(','));
  assert(errors.length === 0, 'No browser exceptions: ' + errors.join(','));
  assert(await page.evaluate(() => localStorage.length === 0 && sessionStorage.length === 0), 'No browser credential persistence');
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('button', { name: '切换为浅色', exact: true }).click();
  return { result: 'PASS', checks: passed, externalRequests: outbound.length, browserErrors: errors.length };
}
