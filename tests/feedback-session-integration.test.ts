import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { startTestHost } from './fixtures/host-process.ts';
import { startSyntheticProvider } from './fixtures/synthetic-provider.ts';
import { readJson } from './fixtures/joint-context.ts';
import { sessionEvents } from './fixtures/session-events.ts';

test('FC10–13/16/18: ordinary native review delivers the selected revision, keeps autonomous tools, and reopens exact receipts', {timeout:90000}, async t=>{
  const provider = await startSyntheticProvider(); t.after(()=>provider.close());
  let host = await startTestHost(); t.after(()=>host.close());
  await readJson(await host.request('/api/configuration','PUT',{name:'反馈合成协议',provider:'openai-compatible',baseUrl:provider.baseUrl,model:'synthetic-feedback',apiKey:'synthetic-feedback-only-key'}));
  const {project} = await readJson(await host.request('/api/projects','POST',{name:'反馈普通会话合成项目'}),201);
  const {item} = await readJson(await host.request('/api/decision-board/items','POST',{projectId:project.id,title:'小范围试点',rationale:'原假设尚未验证'}),201);
  await readJson(await host.request(`/api/decision-board/items/${item.id}/adopt`,'POST',{}));
  const {task:boardTask} = await readJson(await host.request(`/api/decision-board/items/${item.id}/tasks`,'POST',{title:'记录试点',owner:'合成运营',dueDate:''}),201);
  const feedbackInput = {operationId:randomUUID(),expectedLatestRevisionId:null,adopted:true,outcome:'已执行两店试点',metricDelta:'OLD_FEEDBACK_同比口径未核',review:'并行活动存在，不能归因',score:null,effect:'unknown'};
  const {feedback} = await readJson(await host.request(`/api/decision-board/tasks/${boardTask.id}/feedback`,'POST',feedbackInput));
  const {preview} = await readJson(await host.request('/api/decision-feedback/preview','POST',{boardTaskId:boardTask.id,feedbackRevisionId:feedback.revisionId,question:'请自主判断哪些条件还不足，不要求确定效果。',taskName:'自主复盘草稿',caseSelection:null,materials:[{id:'feedback',kind:'feedback',mode:'full'}]}));
  const intent = {operationId:randomUUID(),previewId:preview.previewId};
  const created = await readJson(await host.request('/api/decision-feedback/handoffs','POST',intent),201);
  assert.equal(provider.requests.length,0,'Creating a draft must not send a model request');
  const route = `/api/projects/${project.id}/tasks/${created.task.id}`;
  const input = {requestId:randomUUID(),text:'请自主判断哪些条件还不足，不要求确定效果。',feedbackContext:{handoffId:created.handoff.handoffId,selectedMaterialIds:['feedback']}};
  const stream = await sessionEvents(host,project.id,created.task.id); t.after(()=>stream.close());
  await readJson(await host.request(`${route}/messages`,'POST',input),202); await stream.terminal;
  const state = await readJson(await host.request(route));
  assert.ok(JSON.stringify(provider.requests[0]?.body.messages?.filter((m:any)=>m.role==='user')).includes('OLD_FEEDBACK_同比口径未核'));
  assert.ok(provider.requests[0]?.body.tools?.some((tool:any)=>tool.function?.name==='read'),'Review retains ordinary native tools');
  const context = state.snapshot.capabilities.semanticContext;
  assert.equal(context.claim,'provided-not-adopted');
  assert.equal(context.feedback.feedbackRevisionId,feedback.revisionId);
  assert.equal(context.feedback.materials[0].body.includes('OLD_FEEDBACK_同比口径未核'),true);
  assert.equal(state.snapshot.messages.findLast((m:any)=>m.role==='user').originalUserText,input.text);
  const reply = state.snapshot.messages.findLast((m:any)=>m.role==='assistant'); assert.ok(reply.nativeEntryId);assert.ok(reply.nativeSessionId);
  await readJson(await host.request(`/api/decision-board/tasks/${boardTask.id}/feedback`,'POST',{...feedbackInput,operationId:randomUUID(),expectedLatestRevisionId:feedback.revisionId,metricDelta:'NEW_FEEDBACK_不得替换旧请求'}));
  await readJson(await host.request(`${route}/messages`,'POST',input),202);
  await readJson(await host.request(`${route}/messages`,'POST',{...input,feedbackContext:{...input.feedbackContext,selectedMaterialIds:[]}}),409);
  assert.equal(provider.requests.length,1);
  const nativeBytes = await readFile(state.task.sessionFile);
  await stream.close();await host.close();host=await startTestHost({dataRoot:host.dataRoot,projectsRoot:host.projectsRoot});
  const reopened=await readJson(await host.request(route));assert.deepEqual(reopened.snapshot.capabilities.semanticContext,context);assert.deepEqual(await readFile(state.task.sessionFile),nativeBytes);
});
