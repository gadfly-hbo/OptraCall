import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
const artifact='openspec/changes/agent-brain-external-collaboration/ui-demo.html';
const expected=process.argv[2];
assert.match(expected??'',/^[a-f0-9]{64}$/,'provide the frozen HTML SHA-256');
const out='.local/agent-brain-main-update/root';
const origin='http://127.0.0.1:4317';
const store='optracall.external-collaboration.demo.v2';
const checks=[],errors=[],external=[];
const hash=async()=>createHash('sha256').update(await fs.readFile(artifact)).digest('hex');
const check=(name,ok)=>{assert.ok(ok,name);checks.push(name)};
check('fixed HTML before navigation',await hash()===expected);
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(/^https?:/.test(r.url())&&!r.url().startsWith(origin+'/'))external.push(r.url())});
const state=()=>page.evaluate(key=>JSON.parse(sessionStorage.getItem(key)),store);
const wait=s=>page.waitForFunction(({key,s})=>JSON.parse(sessionStorage.getItem(key)).status===s,{key:store,s},{timeout:25000});
try {
 await page.goto(origin+'/ui-demo.html#home');
 check('one Decision Case primary navigation',await page.getByTestId('nav-cases').count()===1);
 const pending=await page.getByTestId('pending-count').innerText();
 const projectWait=await page.getByTestId('original-project-wait').innerText();
 await page.getByTestId('home-continue-case').click();
 await page.getByTestId('case-discussion').fill('事项草稿：保留原意 <不自动发送>');
 const issueBefore=(await state()).caseUi.issue;
 await page.getByTestId('case-tab-projects').click();
 await page.getByTestId('case-scope').selectOption('all');
 await page.getByTestId('task-analysis').click();
 await page.getByTestId('task-draft').fill('原任务草稿：待核对，保留 <原文>。');
 check('Task carries exact source Case navigation',await page.getByTestId('return-source-case').isVisible());
 await page.getByTestId('authorize-open').click();
 await page.getByTestId('auth-asset-mapping').uncheck();
 await page.setViewportSize({width:390,height:844});
 check('390 grant fits viewport',await page.getByTestId('dialog').evaluate(e=>e.getBoundingClientRect().width<=innerWidth));
 await page.screenshot({path:out+'/grant-390.png'});
 await page.keyboard.press('Tab');
 check('grant keeps keyboard focus inside',await page.getByTestId('dialog').evaluate(e=>e.contains(document.activeElement)));
 await page.keyboard.press('Escape');
 check('Escape restores grant trigger focus',await page.getByTestId('authorize-open').evaluate(e=>e===document.activeElement));
 check('dismissed dialog leaves authorization empty',(await state()).auth===null);
 await page.getByTestId('authorize-open').click();
 await page.getByTestId('auth-asset-mapping').uncheck();
 await page.getByTestId('grant-autonomy').click();
 await wait('accepted');
 const accepted=await state();
 check('one grant autonomously accepts original analysis work',accepted.auth.task==='analysis'&&accepted.status==='accepted');
 check('mapping remains outside actual reads',!accepted.auth.assets.includes('mapping')&&!accepted.reads.some(x=>x.ref==='MAP-004'));
 await page.getByTestId('view-delivery').click();
 check('both artifacts show actual simulated bytes',(await page.getByTestId('preservation-diff').innerText()).includes('已保存字节')&&(await page.getByTestId('preservation-notes').innerText()).includes('已保存字节'));
 await page.getByTestId('open-differences').click();
 const diff=await page.getByTestId('dialog').innerText();
 check('version and mapping restriction stay accurate',diff.includes('v1.0')&&diff.includes('未核验')&&!diff.includes('按映射 v0.4 解释'));
 await page.keyboard.press('Escape');
 await page.getByTestId('delivery-original').click();
 check('original Task draft remains exact',await page.getByTestId('task-draft').inputValue()==='原任务草稿：待核对，保留 <原文>。');
 await page.getByTestId('return-source-case').click();
 check('source Case tab preserved',(await state()).caseUi.tab==='projects');
 check('source Case selected issue preserved',(await state()).caseUi.issue===issueBefore);
 check('manual all-Case scope preserved',await page.getByTestId('case-scope').inputValue()==='all');
 check('focus restored to originating Task link',await page.getByTestId('task-analysis').evaluate(e=>e===document.activeElement));
 check('Case only summarizes original work',await page.getByTestId('case-external-summary').isVisible());
 await page.getByTestId('case-tab-current').click();
 check('original Case draft remains exact',await page.getByTestId('case-discussion').inputValue()==='事项草稿：保留原意 <不自动发送>');
 await page.getByTestId('case-tab-artifacts').click();
 await page.getByTestId('case-original-report').waitFor({state:'visible'});
 check('Case original artifact retained',await page.getByTestId('case-original-report').count()===1);
 check('Case does not automatically list external attachment',!(await page.locator('#main').innerText()).includes('member-differences-v1.0.csv'));
 await page.getByRole('button',{name:'切换工作区',exact:true}).click();
 await page.getByTestId('dialog').getByRole('link',{name:'工作台首页',exact:true}).click();
 await page.getByTestId('home-continue-case').waitFor({state:'visible'});
 check('390 workspace menu returns to actual home',await page.getByTestId('home-continue-case').isVisible());
 check('external acceptance leaves human pending unchanged',await page.getByTestId('pending-count').innerText()===pending);
 check('external acceptance leaves ProjectWork wait unchanged',await page.getByTestId('original-project-wait').innerText()===projectWait);
 await page.getByTestId('scene-select').selectOption('executorbusy');
 await page.getByTestId('authorize-open').click();
 await page.getByTestId('grant-autonomy').click();
 await wait('waiting');
 await page.getByTestId('continue-original').click();
 await page.getByTestId('task-card-pause').click();
 check('idle Task can pause without model or remote cancel',(await state()).paused&&!(await state()).auth.revoked);
 await page.getByTestId('task-card-pause').click();
 check('idle Task resumes only local continuation',!(await state()).paused);
 await page.setViewportSize({width:1024,height:900});
 await page.getByTestId('nav-cases').click();
 await page.getByRole('heading',{name:'Case 总览',exact:true}).waitFor({state:'visible'});
 await page.getByTestId('theme-toggle').click();
 check('1024 dark navigation has no page overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 check('dark short-page root and body share the same canvas',await page.evaluate(()=>getComputedStyle(document.documentElement).backgroundColor===getComputedStyle(document.body).backgroundColor));
 await page.screenshot({path:out+'/cases-1024-dark.png',fullPage:true});
 check('no JavaScript errors',errors.length===0);
 check('no external requests',external.length===0);
 check('fixed HTML after all navigation',await hash()===expected);
 await fs.writeFile(out+'/results.json',JSON.stringify({result:'PASS',expected,checks,errors,external},null,2)+'\n');
 console.log(JSON.stringify({result:'PASS',checks:checks.length,errors,external}));
} catch(e) {
 const stamp=Date.now();
 await page.screenshot({path:out+'/failure-'+stamp+'.png',fullPage:true});
 await fs.copyFile(out+'/check-v02.mjs',out+'/failure-script-'+stamp+'.mjs');
 await fs.writeFile(out+'/failure-'+stamp+'.json',JSON.stringify({result:'FAIL',expected,checks,errors,external,error:String(e)},null,2)+'\n');
 throw e;
} finally {await browser.close()}
